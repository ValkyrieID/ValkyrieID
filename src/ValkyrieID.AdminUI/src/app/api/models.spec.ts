// Schemas the UI models differently: generic pages (Page<T>) and free-form JSON (audit details).
const notModeled = new Set([
  'JsonElement',
  'PageOfClientDto',
  'PageOfGroupDto',
  'PageOfResourceDto',
  'PageOfRoleDto',
  'PageOfUserSummary',
]);

const schemas = openApi.components.schemas as Record<string, { properties?: object }>;

describe('Admin API models', () => {
  it('cover every schema of the OpenAPI document', () => {
    const documented = Object.keys(schemas).filter((name) => !notModeled.has(name));

    expect(Object.keys(types).sort()).toEqual(documented.sort());
  });

  it.each(Object.entries(types))('%s has the documented properties', (name, keys) => {
    expect(Object.keys(keys).sort()).toEqual(Object.keys(schemas[name].properties ?? {}).sort());
  });

  it('pages have items and a total', () => {
    expect(Object.keys(schemas['PageOfUserSummary'].properties ?? {}).sort()).toEqual([
      'items',
      'total',
    ]);
  });
});
